using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.Loader;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

using Xunit;

namespace Sharprompt.SourceGenerator.Tests;

internal static class GeneratorTestHelper
{
    private static readonly CSharpParseOptions s_parseOptions = new(LanguageVersion.Latest);

    private static readonly Lazy<MetadataReference[]> s_references = new(() =>
        ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Append(typeof(Prompt).Assembly.Location)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path))
            .ToArray());

    private static readonly Lazy<ImmutableArray<DiagnosticAnalyzer>> s_trimAnalyzers = new(() =>
        new AnalyzerFileReference(Path.Combine(AppContext.BaseDirectory, "ILLink", "ILLink.RoslynAnalyzer.dll"), new AnalyzerAssemblyLoader())
            .GetAnalyzers(LanguageNames.CSharp));

    // The same switches the SDK sets for a project with IsAotCompatible (or PublishTrimmed / PublishAot).
    private static readonly AnalyzerOptions s_trimAnalyzerOptions = new(
        [],
        new TrimAnalyzerOptionsProvider(new Dictionary<string, string>
        {
            ["build_property.EnableTrimAnalyzer"] = "true",
            ["build_property.EnableAotAnalyzer"] = "true",
        }));

    public static CSharpParseOptions ParseOptions => s_parseOptions;

    public static CSharpCompilation CreateCompilation(params string[] sources)
    {
        return CSharpCompilation.Create(
            "GeneratorTest",
            sources.Select(source => CSharpSyntaxTree.ParseText(source, s_parseOptions, path: "Model.cs")),
            s_references.Value,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
    }

    public static GeneratorDriver CreateDriver(IIncrementalGenerator? generator = null)
    {
        return CSharpGeneratorDriver.Create(
            [(generator ?? new PromptBindableGenerator()).AsSourceGenerator()],
            parseOptions: s_parseOptions,
            driverOptions: new GeneratorDriverOptions(IncrementalGeneratorOutputKind.None, trackIncrementalGeneratorSteps: true));
    }

    public static GeneratorTestResult Run(string source, IIncrementalGenerator? generator = null)
    {
        var compilation = CreateCompilation(source);

        // The test input itself must be valid, so that any error comes from the generated code.
        Assert.Empty(compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error));

        CreateDriver(generator).RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out var generatorDiagnostics);

        var generatedTree = outputCompilation.SyntaxTrees.Skip(1).SingleOrDefault();

        return new GeneratorTestResult(
            compilation.SyntaxTrees.Single().GetText(),
            generatedTree?.ToString(),
            generatorDiagnostics,
            outputCompilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToImmutableArray(),
            outputCompilation);
    }

    // Runs the ILLink trim and AOT analyzers, which report e.g. IL2026 for calls to [RequiresUnreferencedCode] members.
    // The analyzers skip generated code, but ILLink and ILC still warn about it when the consumer publishes,
    // so every syntax tree (including generator output) is analyzed as user code.
    public static ImmutableArray<Diagnostic> GetTrimAnalyzerDiagnostics(Compilation compilation)
    {
        return compilation
            .WithAnalyzers(s_trimAnalyzers.Value, s_trimAnalyzerOptions)
            .GetAnalyzerDiagnosticsAsync()
            .GetAwaiter()
            .GetResult();
    }

    private sealed class AnalyzerAssemblyLoader : IAnalyzerAssemblyLoader
    {
        public void AddDependencyLocation(string fullPath)
        {
        }

        // Loading into the default context binds the analyzer to the Roslyn assemblies the tests already use.
        public Assembly LoadFromPath(string fullPath) => Assembly.LoadFrom(fullPath);
    }

    private sealed class TrimAnalyzerOptionsProvider(IReadOnlyDictionary<string, string> options) : AnalyzerConfigOptionsProvider
    {
        private static readonly AnalyzerConfigOptions s_empty = new DictionaryOptions(new Dictionary<string, string>());

        // Overrides the "<auto-generated/>" and ".g.cs" heuristics, as "generated_code = false" in .editorconfig would.
        private static readonly AnalyzerConfigOptions s_notGenerated = new DictionaryOptions(new Dictionary<string, string> { ["generated_code"] = "false" });

        public override AnalyzerConfigOptions GlobalOptions { get; } = new DictionaryOptions(options);

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => s_notGenerated;

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => s_empty;
    }

    private sealed class DictionaryOptions(IReadOnlyDictionary<string, string> options) : AnalyzerConfigOptions
    {
        public override bool TryGetValue(string key, [NotNullWhen(true)] out string? value) => options.TryGetValue(key, out value);
    }
}

internal sealed record GeneratorTestResult(SourceText Input, string? Source, ImmutableArray<Diagnostic> GeneratorDiagnostics, ImmutableArray<Diagnostic> CompileErrors, Compilation OutputCompilation)
{
    // Loads the generated code into its own context, so that each test gets distinct types even
    // though every test compilation shares the same assembly name.
    public Assembly LoadAssembly()
    {
        AssertGeneratedAndCompiles();

        return EmitAndLoad(OutputCompilation);
    }

    // Compiles a static method with the given body next to the generated code, then runs it. This lets
    // tests execute snippets of the generated binder without driving a prompt.
    public object? Evaluate(string body)
    {
        AssertGeneratedAndCompiles();

        var probe = CSharpSyntaxTree.ParseText("public static class __Probe { public static object? Run() { " + body + " } }", GeneratorTestHelper.ParseOptions, path: "Probe.cs");
        var assembly = EmitAndLoad(OutputCompilation.AddSyntaxTrees(probe));

        return assembly.GetType("__Probe", throwOnError: true)!.GetMethod("Run")!.Invoke(null, null);
    }

    private static Assembly EmitAndLoad(Compilation compilation)
    {
        using var stream = new MemoryStream();

        var emitResult = compilation.Emit(stream);
        Assert.True(emitResult.Success, string.Join(Environment.NewLine, emitResult.Diagnostics));

        stream.Position = 0;

        return new AssemblyLoadContext(name: null).LoadFromStream(stream);
    }

    public string AssertGeneratedAndCompiles()
    {
        Assert.Empty(CompileErrors);
        Assert.NotNull(Source);

        // Sharprompt is IsAotCompatible, so generated binders must not raise trim or AOT warnings in consumers.
        var generatedTree = OutputCompilation.SyntaxTrees.Last();
        Assert.Empty(GeneratorTestHelper.GetTrimAnalyzerDiagnostics(OutputCompilation).Where(d => d.Location.SourceTree == generatedTree));

        return Source;
    }

    // Generator diagnostics must be bound to the input syntax tree (not just a file path), otherwise
    // #pragma warning disable and other source suppressions cannot apply to them.
    public string GetLocationText(Diagnostic diagnostic)
    {
        Assert.True(diagnostic.Location.IsInSource);
        Assert.Equal("Model.cs", diagnostic.Location.SourceTree!.FilePath);

        return Input.ToString(diagnostic.Location.SourceSpan);
    }
}
